/** Cities for a state; includes legacy value if not in the list. */
export function citiesForState(state, currentCity = "") {
  const list = INDIAN_STATE_CITIES[state] || [];
  const current = String(currentCity || "").trim();
  if (!current) return list;
  const exists = list.some((c) => c.toLowerCase() === current.toLowerCase());
  if (exists) return list;
  return [current, ...list];
}
